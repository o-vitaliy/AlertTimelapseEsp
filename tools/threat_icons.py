"""Writes include/ThreatIcons.h from the PNGs in assets/threat_icons.

Each icon is scaled to ICON_SIZE pixels per side and stored as raw RGBA,
pointing north; the firmware turns it to the threat's heading when drawing.
Icons are numbered in the alphabetical order of their file names.

Run it after adding or changing an icon, or a threat type below, then rebuild
and reflash:

    python tools/threat_icons.py

Needs Pillow (pip install pillow).
"""
from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ICON_DIR = ROOT / "assets" / "threat_icons"
OUTPUT = ROOT / "include" / "ThreatIcons.h"
ICON_SIZE = 28  # source pixels per side; drawn smaller, see ICON_SCREEN_SIZE

# NEPTUN threat type -> icon file name (without .png). Types are compared in
# lower case. Other types get UNKNOWN_ICON, and any type containing "group"
# gets GROUP_ICON.
THREAT_TYPES = {
    "uav": "shahed",
    "drone": "shahed",
    "fpv": "fpv",
    "recon": "recon",
    "seadrone": "seadrone",
    "missile": "missile",
    "ballistic": "ballistic",
    "kab": "kab",
    "mig31k": "mig31k",
    "rocket": "missile",
    "mlrs": "mlrs",
    "shell": "mlrs",
    "group": "group",
    "unknown": "unknown",
}
UNKNOWN = "unknown"
GROUP = "group"


def icon_names(icon_dir: Path) -> list[str]:
    return sorted(path.stem for path in icon_dir.glob("*.png"))


def icon_pixels(icon_dir: Path, names: list[str]) -> bytes:
    data = bytearray()
    for name in names:
        icon = Image.open(icon_dir / f"{name}.png").convert("RGBA")
        if icon.size != (ICON_SIZE, ICON_SIZE):
            icon = icon.resize((ICON_SIZE, ICON_SIZE), Image.Resampling.LANCZOS)
        data += icon.tobytes()
    return bytes(data)


def c_bytes(name: str, data: bytes) -> str:
    """A byte array defined in the one file that sets THREAT_ICONS_IMPLEMENTATION."""
    lines = ["#ifdef THREAT_ICONS_IMPLEMENTATION", f"extern const uint8_t {name}[{len(data)}] = {{"]
    for start in range(0, len(data), 24):
        lines.append("  " + ",".join(str(b) for b in data[start : start + 24]) + ",")
    lines += ["};", "#else", f"extern const uint8_t {name}[{len(data)}];", "#endif"]
    return "\n".join(lines)


def build_header(icon_dir: Path) -> str:
    names = icon_names(icon_dir)
    missing = {UNKNOWN, GROUP, *THREAT_TYPES.values()} - set(names)
    if missing:
        raise SystemExit(f"Missing icons in {icon_dir}: {', '.join(sorted(missing))}")
    index = {name: i for i, name in enumerate(names)}
    icon_list = "\n".join(f"//   {i:2} {name}" for i, name in enumerate(names))
    aliases = ",\n".join(f'  {{"{kind}", {index[icon]}}}' for kind, icon in THREAT_TYPES.items())
    return f"""// Generated by tools/threat_icons.py from assets/threat_icons. Do not edit;
// change the icons or the script and run it again.
//
// The array is defined in the one source file that defines
// THREAT_ICONS_IMPLEMENTATION before including this header, and declared
// elsewhere.
#pragma once

#include <stdint.h>

namespace threat_icons {{

// ICON_COUNT square RGBA images of ICON_SIZE pixels, north up:
{icon_list}
constexpr uint8_t ICON_COUNT = {len(names)};
constexpr int16_t ICON_SIZE = {ICON_SIZE};
{c_bytes("ICON_RGBA", icon_pixels(icon_dir, names))}

// NEPTUN threat type -> icon index. Other types use UNKNOWN_ICON, and any type
// containing "group" uses GROUP_ICON.
struct ThreatIcon {{
  const char* type;
  uint8_t icon;
}};
constexpr uint8_t UNKNOWN_ICON = {index[UNKNOWN]};
constexpr uint8_t GROUP_ICON = {index[GROUP]};
constexpr uint8_t THREAT_ICON_COUNT = {len(THREAT_TYPES)};
constexpr ThreatIcon THREAT_ICONS[THREAT_ICON_COUNT] = {{
{aliases}
}};

}}  // namespace threat_icons
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--icons", type=Path, default=ICON_DIR)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    args.output.write_text(build_header(args.icons))
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
